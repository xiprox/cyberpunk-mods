"""Builds the mod's ArchiveXL archive of twin looks for every catalog (RECORD.md, 2026-11-05 and 2026-11-06).

For each catalog in catalog/out/*.json, a patch entity file adds two entries of our own for every look the
catalog's entity file offers, <look>__vc_a and <look>__vc_b, pointing at the same look in the same .app: the
engine rebuilds a car where it stands by switching between them, and a build carrying one of these names is
always the customizer's. Each patch is limited to the `appearances` list in the .xl, so the rest of the patch
file, a copy of the Hella's (catalog/templates/entity_patch.ent.json), is ignored.

Steps: patch JSON per catalog in build/twins/, WolvenKit turns them into .ent files, WolvenKit packs them as
mod/archive/pc/mod/vehiclecustomizer/vehiclecustomizer.archive, and the .xl next to it lists every patch and its
target. They sit in a folder of their own so the log collector's Mods tab, which shares top-level folders only,
can send them to the crew (RECORD.md, 2026-11-06 evening).

Usage: python -I make-twins.py
"""
import copy
import glob
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
WOLVENKIT = r"H:\WolvenKit\Console\WolvenKit.CLI.exe"
BUILD = os.path.join(ROOT, "build", "twins")
PACK_ROOT = os.path.join(BUILD, "vehiclecustomizer")  # its name becomes the archive's
DEPOT = r"vehicle_customizer\twins"
MOD_ARCHIVE = os.path.join(ROOT, "mod", "archive", "pc", "mod", "vehiclecustomizer")
TWINS = ("__vc_a", "__vc_b")


def cname(value):
    return {"$type": "CName", "$storage": "string", "$value": value}


def main():
    template = json.load(open(os.path.join(HERE, "templates", "entity_patch.ent.json"), encoding="utf-8"))
    if os.path.isdir(BUILD):
        shutil.rmtree(BUILD)
    json_dir = os.path.join(BUILD, "json")
    out_dir = os.path.join(PACK_ROOT, DEPOT)
    os.makedirs(json_dir)
    os.makedirs(out_dir)
    patches = []
    for path in sorted(glob.glob(os.path.join(HERE, "out", "*.json"))):
        cat = json.load(open(path, encoding="utf-8"))
        entries = []
        for look, info in sorted(cat["looks"].items()):
            for suffix in TWINS:
                entries.append({
                    "$type": "entTemplateAppearance",
                    "appearanceName": cname(info["app_look"]),
                    "appearanceResource": {"DepotPath": {"$type": "ResourcePath", "$storage": "string",
                                                         "$value": info["app"]}, "Flags": "Soft"},
                    "name": cname(look + suffix),
                })
        if not entries:
            continue
        doc = copy.deepcopy(template)
        doc["Data"]["RootChunk"]["appearances"] = entries
        name = f"{cat['id']}.ent"
        with open(os.path.join(json_dir, name + ".json"), "w", encoding="utf-8") as f:
            json.dump(doc, f)
        patches.append((cat["id"], cat["entity"], len(entries)))
    print(f"{len(patches)} patch files, {sum(n for *_, n in patches)} twin entries")

    result = subprocess.run([WOLVENKIT, "convert", "deserialize", json_dir, "-o", out_dir],
                            capture_output=True, text=True)
    made = glob.glob(os.path.join(out_dir, "*.ent"))
    print(f"WolvenKit made {len(made)} .ent files (exit {result.returncode})")
    if len(made) != len(patches):
        print(result.stdout[-3000:], result.stderr[-2000:])
        sys.exit("not every patch was converted")

    os.makedirs(MOD_ARCHIVE, exist_ok=True)
    result = subprocess.run([WOLVENKIT, "pack", PACK_ROOT, "-o", MOD_ARCHIVE], capture_output=True, text=True)
    archive = os.path.join(MOD_ARCHIVE, "vehiclecustomizer.archive")
    print(f"packed {archive}: {os.path.getsize(archive) if os.path.exists(archive) else 'MISSING'} bytes (exit {result.returncode})")

    lines = ["# Generated by catalog/make-twins.py; don't edit by hand.",
             "# Twin looks, <look>__vc_a and <look>__vc_b, for every catalog's entity file, so the customizer can",
             "# rebuild a car where it stands. Only each entity file's look list is patched.",
             "resource:", "  patch:"]
    for cid, entity, _ in patches:
        lines += [f"    {DEPOT}\\{cid}.ent:", "      props:", "        - appearances", "      targets:",
                  f"        - {entity}"]
    with open(archive + ".xl", "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", archive + ".xl")


if __name__ == "__main__":
    main()
